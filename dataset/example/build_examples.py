def _record_0001() -> DatasetRecord:
    scene = load_scene_graph(FIXTURES / "naksa_base.scene.json")
    _humanise(scene, "fixtures/naksa_base.scene.json (extraction cross-checked by a human annotator)")
    scope_all = _scope(["cc-by-4.0"])
    return DatasetRecord(
        record_id="karmi-example-0001",
        synthetic=True,
        source_kind=scene.source_kind,
        jurisdiction=Jurisdiction(municipality="Kathmandu Metropolitan City", district="Kathmandu"),
        consent=Consent(
            grants=[
                _grant([ConsentRole.HOMEOWNER], scope_all, "form-ex-0001-h",
                       "synthetic example — no real form exists"),
                _grant([ConsentRole.DRAWING_AUTHOR], scope_all, "form-ex-0001-d",
                       "synthetic example — no real form exists"),
                _grant([ConsentRole.PHOTOGRAPHER], scope_all, "form-ex-0001-p",
                       "synthetic example — no real form exists"),
            ]
        ),
        licence=Licence(id=LicenceId.CC_BY_4_0, attribution="Karmi fixtures (synthetic)"),
        release_tier=ReleaseTier.PUBLIC,
        drawing=DrawingAnnotation(
            scene=scene,
            page_files=["drawing/page-01.png"],
            original_sha256=_sha256_file(FIXTURES / "naksa_base.pdf"),
            provenance=Provenance(source="human_annotation", confidence=1.0, evidence=_HUMAN),
            notes="synthetic example — redacted page render would live at drawing/page-01.png in a real release",
        ),
        photos=[
            _photo_annotation("photos/p01-front.jpg", "front_walls_stage.jpg"),
            _photo_annotation("photos/p02-side.jpg", "side_columns_stage.jpg"),
            _photo_annotation("photos/p03-rear.jpg", "rear_foundation_stage.jpg"),
        ],
        annotator=Annotator(annotator_id="ann-001", role="core_team", tool="dataset/annotate.html"),
        quality=_quality(reviewed=True, completeness=0.9),
        notes=(
            "SYNTHETIC EXAMPLE (not collected data). Single-storey plan from the repository "
            "fixture; demonstrates a fully-consented CC BY 4.0 record with photos across "
            "three construction stages."
        ),
        created_at=datetime(2026, 10, 4, 12, 0, tzinfo=timezone.utc),
    )


