# --------------------------------------------------------------------------- #
# build
# --------------------------------------------------------------------------- #
def build_examples(*, verbose: bool = True) -> dict[str, Any]:
    """(Re)generate every example artefact. Returns a manifest dict."""
    records: list[DatasetRecord] = [_record_0001(), _record_0002(), _record_0003()]

    # De-identify every fixture photo that the records reference (media/ copies).
    photo_meta: dict[str, dict[str, Any]] = {}
    for fixture in ("front_walls_stage.jpg", "side_columns_stage.jpg",
                    "rear_foundation_stage.jpg", "interior_unknown.jpg"):
        clean, meta = _clean_fixture_photo(fixture)
        photo_meta[fixture] = {
            "clean_copy": clean.name,
            "gps_present_before": meta.get("gps_present_before"),
            "gps_present_after": meta.get("gps_present_after"),
            "exif_fields_removed": meta.get("exif_fields_removed"),
        }

    manifest: dict[str, Any] = {
        "schema": "karmi-example-manifest/0.1.0",
        "synthetic": True,
        "warning": (
            "Every record in this directory is SYNTHETIC — generated from the repository's "
            "own fixtures. No real building, person or consent form is involved."
        ),
        "generated_by": "dataset/example/build_examples.py",
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "records": [],
        "media": photo_meta,
    }

    for rec in records:
        findings = scan_record(rec)
        path = rec.save(EXAMPLE_DIR / f"{rec.record_id}.json")
        manifest["records"].append(
            {
                "record_id": rec.record_id,
                "file": path.name,
                "sha256": hashlib.sha256(rec.model_dump_json().encode("utf-8")).hexdigest(),
                "withdrawn": rec.consent.withdrawn,
                "tier": rec.release_tier.value,
                "licence": rec.licence.id.value,
                "pii_findings_from_scan": len(findings),
                "summary": rec.summary(),
            }
        )
        if verbose:
            state = "WITHDRAWN" if rec.consent.withdrawn else rec.release_tier.value
            print(f"wrote {path.name}  [{state}]  {rec.summary()}")
        if findings:
            print(f"  !! {len(findings)} PII candidate(s) found by scan_record:")
            for f in findings:
                print(f"     - [{f.category}] {f.masked} at {f.location}")

    (EXAMPLE_DIR / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    if verbose:
        print(f"wrote manifest.json  ({len(records)} record(s))")
        print("all records are SYNTHETIC (fixture-derived); no real data is involved.")
    return manifest


if __name__ == "__main__":
    build_examples()