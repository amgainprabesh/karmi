EXAMPLE_DIR = Path(__file__).resolve().parent
REPO_ROOT = EXAMPLE_DIR.parents[1]
FIXTURES = REPO_ROOT / "fixtures"
MEDIA_DIR = EXAMPLE_DIR / "media"

# Fixed synthetic dates — deterministic output, clearly not real collection dates.
GRANT_DATE = date(2026, 6, 1)
WITHDRAW_AT = datetime(2026, 9, 20, 11, 30, tzinfo=timezone.utc)
SYNTHETIC_CAPTURE_AT = "2026-06-15T09:00:00+05:45"

_HUMAN = "human-annotated ground truth (synthetic example)"


# --------------------------------------------------------------------------- #
# helpers
# --------------------------------------------------------------------------- #
def _sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _humanise(scene: SceneGraph, note: str) -> SceneGraph:
    """Re-stamp extraction provenance as human annotation (dataset-plan §2.2).

    The fixture scenes were produced by the deterministic extractor; in a
    dataset record the values are *verified ground truth*, which is exactly what
    the ``human_annotation`` provenance literal exists for.
    """
    evidence = f"{_HUMAN}: {note}"
    for w in scene.walls:
        w.provenance = Provenance(source="human_annotation", confidence=w.provenance.confidence, evidence=evidence)
    for o in scene.openings:
        o.provenance = Provenance(source="human_annotation", confidence=o.provenance.confidence, evidence=evidence)
    for r in scene.rooms:
        r.provenance = Provenance(source="human_annotation", confidence=r.provenance.confidence, evidence=evidence)
    for d in scene.dimensions:
        d.provenance = Provenance(source="human_annotation", confidence=d.provenance.confidence, evidence=evidence)
    if scene.north_deg is not None:
        scene.north_provenance = Provenance(source="human_annotation", confidence=0.9, evidence=evidence)
    if scene.scale_m_per_unit is not None:
        scene.scale_provenance = Provenance(source="human_annotation", confidence=0.9, evidence=evidence)
    scene.meta["dataset_note"] = note
    return scene


def _clean_fixture_photo(fixture_name: str) -> tuple[Path, dict[str, Any]]:
    """EXIF-strip one fixture photo into dataset/example/media/ (+ report)."""
    MEDIA_DIR.mkdir(parents=True, exist_ok=True)
    src = FIXTURES / "photos" / fixture_name
    clean = MEDIA_DIR / (Path(fixture_name).stem + ".clean" + Path(fixture_name).suffix.lower())
    report = deidentify_photo(src, clean)
    report.save(MEDIA_DIR / (clean.stem + ".deid-report.json"))
    return clean, report.metadata


def _photo_annotation(
    release_file: str,
    fixture_name: str,
    *,
    notes: str | None = None,
) -> PhotoAnnotation:
    """Build one PhotoAnnotation from a fixture photo + its sidecar (if any)."""
    src = FIXTURES / "photos" / fixture_name
    observed = to_observed_state([src])

    # The record describes the *released* photo, not the contributor's file:
    # replace the local path with the opaque release name.
    for cap in observed.captures:
        cap.file = release_file
        if not cap.taken_at:
            cap.taken_at = SYNTHETIC_CAPTURE_AT
        cap.provenance = Provenance(
            source="human_annotation",
            confidence=cap.stage_confidence,
            evidence=f"{_HUMAN}: view/stage labels checked against the fixture sidecar",
        )
    for el in observed.elements:
        el.provenance = Provenance(
            source="human_annotation",
            confidence=el.provenance.confidence,
            evidence=f"{_HUMAN}: {el.provenance.evidence or 'sidecar measurement'}",
        )
    for ref in observed.scale_refs:
        ref.provenance = Provenance(
            source="human_annotation",
            confidence=ref.provenance.confidence,
            evidence=f"{_HUMAN}: {ref.provenance.evidence or 'sidecar scale reference'}",
        )

    return PhotoAnnotation(
        file=release_file,
        observed=observed,
        original_sha256=_sha256_file(src),
        redacted=True,  # the media/ copy is EXIF-stripped by this builder
        provenance=Provenance(source="human_annotation", confidence=1.0, evidence=_HUMAN),
        notes=notes or (
            "synthetic example — derived from the repository fixture "
            f"fixtures/photos/{fixture_name}; EXIF-stripped copy + report in dataset/example/media/"
        ),
    )


def _scope(licences: list[str], *, release: bool = True, training: bool = True,
           restrictions: list[str] | None = None) -> ConsentScope:
    return ConsentScope(
        licence_scope=[LicenceId(x) for x in licences],
        dataset_release=release,
        model_training=training,
        restrictions=restrictions or [],
    )


def _grant(
    roles: list[ConsentRole],
    scope: ConsentScope,
    signatory_id: str,
    evidence: str,
) -> ConsentGrant:
    return ConsentGrant(
        roles=roles,
        method=ConsentMethod.WRITTEN_FORM,
        granted_at=GRANT_DATE,
        scope=scope,
        signatory_id=signatory_id,
        evidence=evidence,
    )


def _quality(reviewed: bool, completeness: float, issues: list[str] | None = None) -> AnnotationQuality:
    return AnnotationQuality(
        reviewed=reviewed,
        double_annotated=False,
        n_annotators=1,
        completeness=completeness,
        issues=issues or [],
    )


