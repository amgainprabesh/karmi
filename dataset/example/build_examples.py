"""Build the synthetic example records for ``dataset/example/``.

Run::

    python -m dataset.example.build_examples
    # or from the repo root:
    ./.venv/Scripts/python.exe -m dataset.example.build_examples

Everything this writes is **synthetic**: the drawings come from
``fixtures/naksa_base.pdf`` / ``fixtures/naksa_drift.pdf`` and the photos from
``fixtures/photos/`` — the repository's own fixtures, which describe no real
building and no real person. Three records are produced:

* ``karmi-example-0001`` — full consent (homeowner + drawing author +
  photographer), CC BY 4.0, three photos across construction stages.
* ``karmi-example-0002`` — narrower licence (CC BY-NC 4.0), one grant covering
  two roles (the homeowner also took the photos), scene extracted live from
  ``fixtures/naksa_drift.pdf``.
* ``karmi-example-0003`` — a **withdrawn consent**, so the redaction path is
  exercised end-to-end: the record is marked withdrawn and a redaction
  instruction is written next to it. ``dataset.export`` refuses to export it.

The builder also runs ``dataset.deidentify.deidentify_photo`` on each fixture
photo used (EXIF strip + report, written under ``dataset/example/media/``) and
``scan_record`` over every finished record — the build fails loudly if a record
trips a PII heuristic.

The JSON is generated by running this code, never by hand; re-running is
idempotent and deterministic (fixed dates, fixed seed values, no clock reads in
the record content).
"""

