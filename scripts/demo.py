#!/usr/bin/env python3
"""Karmi demo — the one command that shows the whole product working.

Runs the full offline pipeline on the sample naksa drawing + the three sample
site photos + their hand-measurement sidecars, writes every artifact to
``runs/demo/``, and prints a presentable summary: severity counts, the headline
finding in English and Nepali, the coverage/limits lines, and the path of every
file it wrote. Also writes ``runs/demo/DEMO.md`` — a short walkthrough of what
the run shows and what the honest limits are.

No network, no GPU, no API key, no AI model — everything here is deterministic.

Usage (from the repository root, with the project venv)::

    python scripts/demo.py
    python scripts/demo.py --out runs/demo --open
    python scripts/demo.py --json

Exit code: 0 on a clean run, 1 if the pipeline reports errors or an expected
artifact is missing, 2 if the fixtures are not where they should be.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

DRAWING_REL = "fixtures/naksa_base.pdf"
PHOTO_NAMES = (
    "front_walls_stage.jpg",
    "rear_foundation_stage.jpg",
    "side_columns_stage.jpg",
)
#: hand-measurement sidecars, one per measured photo (``<photo>.json``)
SIDECAR_NAMES = tuple(f"{n}.json" for n in PHOTO_NAMES)
KNOWN_DIMENSION_M = 10.0

SEV_ORDER = ("high", "medium", "low", "info")
STATUS_ORDER = {"differs": 0, "missing": 1, "unexpected": 2, "unverifiable": 3, "matched": 4}

#: key in PipelineResult.files -> filename printed in the artifact list
ARTIFACT_FILES = (
    ("report_html", "report.html"),
    ("report_md", "report.md"),
    ("report", "report.json"),
    ("view", "view.json"),
    ("scene", "scene.json"),
    ("observed", "observed.json"),
    ("run", "run.json"),
)


def _sev(delta) -> str:
    sev = getattr(delta, "severity", "info")
    return str(getattr(sev, "value", sev) or "info").lower()


def _status(delta) -> str:
    st = getattr(delta, "status", "unverifiable")
    return str(getattr(st, "value", st) or "unverifiable").lower()


def _display(path: Path) -> str:
    """Path as shown to the user: repo-relative when possible, else absolute."""
    try:
        return str(Path(path).resolve().relative_to(REPO_ROOT))
    except (ValueError, OSError):
        return str(path)


def pick_headline(deltas):
    """The most significant delta: highest severity, then the most telling status.

    'differs' beats 'missing'/'unexpected'/'unverifiable'; a matched or info-only
    delta is only chosen when nothing else exists (the caller decides how to
    phrase that).
    """
    def key(d):
        sev = _sev(d)
        st = _status(d)
        try:
            conf = float(getattr(d, "confidence", 0.0) or 0.0)
        except (TypeError, ValueError):
            conf = 0.0
        return (
            SEV_ORDER.index(sev) if sev in SEV_ORDER else 9,
            STATUS_ORDER.get(st, 9),
            -conf,
        )

    return sorted(deltas, key=key)[0] if deltas else None


def headline_dict(delta) -> dict | None:
    if delta is None:
        return None
    try:
        conf = float(getattr(delta, "confidence", 0.0) or 0.0)
    except (TypeError, ValueError):
        conf = 0.0
    return {
        "id": delta.id,
        "element": delta.element,
        "status": _status(delta),
        "severity": _sev(delta),
        "confidence": round(conf, 2),
        "expected": delta.expected,
        "observed": delta.observed,
        "reason_en": delta.reason,
        "reason_np": delta.reason_np,
    }


def build_demo_md(summary: dict, headline: dict | None, limits: list[str],
                  artifacts: list[tuple[str, str, bool]], errors: list[str],
                  warnings: list[str], differences: list[dict] | None = None) -> str:
    lines: list[str] = []
    lines.append("# Karmi demo run — what this shows")
    lines.append("")
    lines.append(
        "Generated by `python scripts/demo.py` — the full pipeline, end to end, "
        "with **no network, no GPU, no API key and no AI model**. Everything in "
        "this folder is deterministic and reproducible."
    )
    lines.append("")
    lines.append("## Inputs")
    lines.append("")
    lines.append("- Approved drawing: `fixtures/naksa_base.pdf` (synthetic sample naksa, vector PDF)")
    lines.append("- Site photos (3, synthetic): " + ", ".join(f"`fixtures/photos/{n}`" for n in PHOTO_NAMES))
    lines.append("- Hand measurement sidecars (tape-measured, synthetic): "
                 + ", ".join(f"`fixtures/photos/{n}`" for n in SIDECAR_NAMES))
    lines.append(f"- Known dimension: {KNOWN_DIMENSION_M} m")
    lines.append("")
    lines.append("## Result at a glance")
    lines.append("")
    lines.append(
        f"- **{summary.get('total', 0)}** elements compared, "
        f"**{summary.get('matched', 0)}** matched the drawing, "
        f"**{summary.get('verify_items', 0)}** items to verify."
    )
    lines.append(
        f"- Severity: **high {summary.get('high', 0)}** · medium {summary.get('medium', 0)} · "
        f"low {summary.get('low', 0)} · info {summary.get('info', 0)}."
    )
    lines.append("")
    lines.append("## The headline finding")
    lines.append("")
    if headline is not None and headline.get("status") not in (None, "matched"):
        lines.append(
            f"**{headline['element']}** — the drawing says **{headline['expected']}**; "
            f"the site evidence suggests **{headline['observed']}** "
            f"(severity {headline['severity']}, confidence {headline['confidence']})."
        )
        lines.append("")
        if headline.get("reason_en"):
            lines.append(f"> **EN:** {headline['reason_en']}")
        if headline.get("reason_np"):
            lines.append(f"> ")
            lines.append(f"> **NE:** {headline['reason_np']}")
        lines.append("")
        lines.append(
            "This is an *item to verify*, not a violation — Karmi never declares a violation. "
            "Only your architect or your municipality can decide whether a change is acceptable."
        )
    else:
        lines.append(
            "No difference above the info threshold was flagged in this run. That is not proof "
            "that everything is correct — photos only show what they show."
        )
    lines.append("")
    if differences:
        lines.append("## Every difference flagged")
        lines.append("")
        lines.append("| Severity | Element | Drawing | Site evidence | Confidence |")
        lines.append("|---|---|---|---|---|")
        for d in differences:
            lines.append(
                f"| {d['severity']} | {d['element']} | {d['expected'] or '—'} | "
                f"{d['observed'] or '—'} | {d['confidence']} |"
            )
        lines.append("")
    lines.append("## Coverage & limits (what this run could NOT determine)")
    lines.append("")
    if limits:
        for limit in limits:
            lines.append(f"- {limit}")
    else:
        lines.append("- (none recorded)")
    lines.append("")
    lines.append("## Artifacts in this folder")
    lines.append("")
    for label, rel, exists in artifacts:
        mark = "" if exists else "  **(MISSING)**"
        lines.append(f"- `{rel}` — {label}{mark}")
    lines.append("")
    lines.append("## Honest notes")
    lines.append("")
    lines.append(
        "- Every drawing and photo here is **synthetic** — generated by `fixtures/make_naksa.py` "
        "and Pillow. No real person's plan or house is in this repo."
    )
    lines.append(
        "- The sidecar measurements are hand-entered demo numbers. Sizes read from photos "
        "without a sidecar are estimates with a confidence value — never measured facts."
    )
    lines.append(
        "- Karmi checks layout and visible size only: no structure, steel, soil or engineering "
        "safety. This is not a legal document and not a municipal inspection."
    )
    lines.append("")
    lines.append("## Reproduce")
    lines.append("")
    lines.append("```bash")
    lines.append("python scripts/demo.py            # rewrite this folder from scratch")
    lines.append("python scripts/demo.py --open     # ... and open report.html in your browser")
    lines.append("python scripts/demo.py --json     # machine-readable summary on stdout")
    lines.append("```")
    if errors:
        lines.append("")
        lines.append("## ERRORS recorded by this run")
        lines.append("")
        for e in errors:
            lines.append(f"- `{e}`")
    if warnings:
        lines.append("")
        lines.append("## Warnings recorded by this run")
        lines.append("")
        for w in warnings:
            lines.append(f"- {w}")
    lines.append("")
    return "\n".join(lines)


def open_report(path: Path) -> None:
    try:
        if hasattr(os, "startfile"):  # Windows
            os.startfile(str(path))  # type: ignore[attr-defined]
        else:
            import webbrowser

            webbrowser.open(path.as_uri())
        print(f"opened {_display(path)} in the default browser")
    except Exception as exc:  # noqa: BLE001 — opening the report is a convenience, never fatal
        print(f"warning: could not open the report ({type(exc).__name__}: {exc})", file=sys.stderr)


def main(argv=None) -> int:
    try:  # Nepali must survive any console/pipe encoding
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")  # type: ignore[union-attr]
        sys.stderr.reconfigure(encoding="utf-8", errors="replace")  # type: ignore[union-attr]
    except Exception:
        pass

    ap = argparse.ArgumentParser(
        prog="python scripts/demo.py",
        description="Run the full Karmi pipeline on the sample naksa + site photos (offline) "
                    "and print a presentable summary.",
    )
    ap.add_argument("--drawing", default=str(REPO_ROOT / DRAWING_REL),
                    help=f"path to architectural drawing PDF (default: {DRAWING_REL})")
    ap.add_argument("--out", default=str(REPO_ROOT / "runs" / "demo"),
                    help="output directory (default: runs/demo)")
    ap.add_argument("--open", action="store_true",
                    help="open report.html in the default browser when done")
    ap.add_argument("--json", action="store_true",
                    help="print only a machine-readable JSON summary")
    args = ap.parse_args(argv)

    drawing = Path(args.drawing).expanduser().resolve()
    photos = [REPO_ROOT / "fixtures" / "photos" / n for n in PHOTO_NAMES]
    sidecars = [REPO_ROOT / "fixtures" / "photos" / n for n in SIDECAR_NAMES]
    missing_inputs = [p for p in [drawing, *photos, *sidecars] if not p.is_file()]
    if missing_inputs:
        for p in missing_inputs:
            print(f"error: file not found: {p}", file=sys.stderr)
        print("Run this from a full checkout of the repository (fixtures/ must exist).", file=sys.stderr)
        return 2

    out_dir = Path(args.out).expanduser().resolve()

    from core.pipeline import run_pipeline

    res = run_pipeline(
        str(drawing),
        [str(p) for p in photos],
        out_dir=str(out_dir),
        known_dimension=KNOWN_DIMENSION_M,
        sidecars={str(p): str(s) for p, s in zip(photos, sidecars)},
    )

    report = res.report
    summary = dict(report.summary) if report is not None else {}
    deltas = list(report.deltas) if report is not None else []
    limits = list(report.limits) if report is not None else []
    headline = headline_dict(pick_headline(deltas))
    differences = [
        headline_dict(d)
        for d in sorted(
            (d for d in deltas if _status(d) in ("differs", "missing", "unexpected")),
            key=lambda d: SEV_ORDER.index(_sev(d)) if _sev(d) in SEV_ORDER else 9,
        )
    ]

    # ---- artifact bookkeeping -------------------------------------------------
    # run_pipeline writes fixed filenames into out_dir; list them all and verify
    # on disk afterwards (a file that should be there but is not = failure).
    artifact_paths: list[tuple[str, Path]] = [
        (name, out_dir / name) for _key, name in ARTIFACT_FILES
    ]
    demo_md_path = out_dir / "DEMO.md"

    missing_artifacts = [name for name, p in artifact_paths if not p.is_file()]
    ok = not res.errors and report is not None and not missing_artifacts

    # ---- DEMO.md --------------------------------------------------------------
    demo_md = build_demo_md(
        summary,
        headline,
        limits,
        [(name, _display(p), p.is_file()) for name, p in artifact_paths]
        + [("DEMO.md — this walkthrough", _display(demo_md_path), True)],
        res.errors,
        res.warnings,
        differences,
    )
    out_dir.mkdir(parents=True, exist_ok=True)
    demo_md_path.write_text(demo_md, encoding="utf-8")

    files_payload = {name: _display(p) for name, p in artifact_paths}
    files_payload["DEMO.md"] = _display(demo_md_path)

    # ---- output ----------------------------------------------------------------
    if args.json:
        payload = {
            "ok": ok,
            "out_dir": _display(out_dir),
            "drawing": DRAWING_REL,
            "photos": [f"fixtures/photos/{n}" for n in PHOTO_NAMES],
            "sidecars": [f"fixtures/photos/{n}" for n in SIDECAR_NAMES],
            "known_dimension_m": KNOWN_DIMENSION_M,
            "engine": {"ai": "none", "network": False, "deterministic": True},
            "summary": summary,
            "headline": headline,
            "differences": differences,
            "limits": limits,
            "narration_en": list(report.narration_en) if report is not None else [],
            "narration_np": list(report.narration_np) if report is not None else [],
            "files": files_payload,
            "errors": list(res.errors),
            "warnings": list(res.warnings),
            "timings_ms": dict(res.timings_ms),
        }
        print(json.dumps(payload, ensure_ascii=False, indent=2))
    else:
        print("Karmi demo — approved naksa vs site evidence, fully offline")
        print("=" * 62)
        print(f"drawing   : {DRAWING_REL}")
        print(f"photos    : {len(PHOTO_NAMES)}  ({', '.join(PHOTO_NAMES)})")
        print(f"sidecars  : {len(SIDECAR_NAMES)}  (hand measurements, one per photo)")
        print(f"known dim : {KNOWN_DIMENSION_M} m")
        print(f"out dir   : {_display(out_dir)}")
        print("engine    : no AI · no network · deterministic")
        print()
        timings = ", ".join(f"{k} {v} ms" for k, v in res.timings_ms.items())
        print(f"Run       : {'OK — no errors' if not res.errors else 'ERRORS — see below'}"
              + (f"  ({timings})" if timings else ""))
        print(f"Severity  : high {summary.get('high', 0)} · medium {summary.get('medium', 0)} · "
              f"low {summary.get('low', 0)} · info {summary.get('info', 0)}")
        print(f"Compared  : {summary.get('total', 0)} elements, {summary.get('matched', 0)} matched the "
              f"drawing, {summary.get('verify_items', 0)} items to verify")
        print()
        print("Headline finding")
        print("-" * 62)
        if headline is not None and headline["status"] != "matched":
            print(f"  element  : {headline['element']}  [{headline['id']}]")
            print(f"  severity : {headline['severity']}  (confidence {headline['confidence']})")
            print(f"  drawing  : {headline['expected']}")
            print(f"  site     : {headline['observed']}")
            print(f"  EN : {headline['reason_en']}")
            print(f"  NE : {headline['reason_np']}")
        else:
            print("  No difference above the info threshold was flagged in this run.")
        if len(differences) > 1:
            print()
            print(f"All differences ({len(differences)})")
            print("-" * 62)
            for d in differences:
                print(f"  [{d['severity']:<6}] {d['element']}: drawing {d['expected'] or '—'} "
                      f"vs site {d['observed'] or '—'}  (conf {d['confidence']})")
        print()
        print("These are items to verify — Karmi never declares a violation.")
        print()
        print("Coverage & limits (what this run could NOT determine)")
        print("-" * 62)
        for limit in limits:
            print(f"  - {limit}")
        if not limits:
            print("  (none recorded)")
        print()
        print("Artifacts written")
        print("-" * 62)
        for name, p in artifact_paths:
            mark = "" if p.is_file() else "   [MISSING]"
            print(f"  {_display(p)}{mark}")
        print(f"  {_display(demo_md_path)}")
        print()
        print(f"Read the full report: {_display(out_dir / 'report.html')}  (re-run with --open to launch it)")

    if res.errors:
        print("Pipeline errors:", file=sys.stderr)
        for e in res.errors:
            print(f"  - {e}", file=sys.stderr)
    if missing_artifacts:
        print(f"Missing expected artifacts: {', '.join(missing_artifacts)}", file=sys.stderr)

    if args.open:
        open_report(out_dir / "report.html")

    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())